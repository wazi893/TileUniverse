/// Maps control signals to tile configurations
///
/// This is used by the builder to create the control unit tiles.
pub struct ControlUnitLayout {
    /// Tiles needed for opcode decode
    pub decode_tiles: usize,
    /// Tiles needed for register select
    pub reg_select_tiles: usize,
    /// Tiles needed for ALU mux control
    pub alu_mux_tiles: usize,
    /// Tiles needed for branch logic
    pub branch_tiles: usize,
}

impl ControlUnitLayout {
    /// Calculate layout for a given instruction set
    pub fn for_instruction_set() -> Self {
        Self {
            // 4-bit opcode → 16 one-hot lines = 2 Decoder3to8 tiles
            decode_tiles: 2,
            // 2-bit reg select × 2 = 2 Decoder3to8 tiles
            reg_select_tiles: 2,
            // 5 ALU ops → Mux8to1 tile
            alu_mux_tiles: 1,
            // Branch conditions: And, Or, Mux tiles
            branch_tiles: 4,
        }
    }

    pub fn total_tiles(&self) -> usize {
        self.decode_tiles + self.reg_select_tiles + self.alu_mux_tiles + self.branch_tiles
    }
}

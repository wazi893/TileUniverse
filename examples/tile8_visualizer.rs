fn window_conf() -> Conf {
    Conf {
        window_title: "TILE-8 Visualizer".to_string(),
        window_width: 1600,
        window_height: 900,
        window_resizable: true,
        high_dpi: true,
        ..Default::default()
    }
}

#[macroquad::main(window_conf)]
async fn main() {
    // Parse arguments: --benchmark, --size <N>, or --selector
    let args: Vec<String> = std::env::args().collect();
    let mut cpu_count = 10_000;
    let mut spacing = 2; // GPU layout is 3x3, spacing=2 means shared registers (Hive!)
    let mut run_benchmark = false;
    let mut selector_mode = false;

    for i in 0..args.len() {
        if args[i] == "--benchmark" {
            // DENSE HIVE: Every CPU is connected! 12288/2 = 6144x6144 = 37.7 MILLION CPUs
            cpu_count = 37_748_736;
            spacing = 2;
            run_benchmark = true;
            println!("Benchmark Mode: 37.7M CPUs in 151M tiles (PERFECT MESH HIVE!)");
        }
        if args[i] == "--size" && i + 1 < args.len() {
            if let Ok(n) = args[i + 1].parse::<usize>() {
                cpu_count = n;
            }
        }
        if args[i] == "--selector" {
            selector_mode = true;
            println!("Selector Mode: Fitness-based evolutionary selection (Sprint 66)");
        }
    }

    println!("Initializing {} CPUs...", format_thousands(cpu_count));
    let mut viz = Visualizer::new_with_mode(cpu_count, spacing, selector_mode).await;

    if run_benchmark {
        // Position camera to see something interesting
        viz.target_zoom = 0.005;
        // viz.running = true; // Start running immediately
    }

    #[cfg(feature = "gpu-prototype")]
    let mut gpu_texture: Option<Texture2D> = None;

    loop {
        let dt = get_frame_time();
        clear_background(BG_COLOR);

        let mut captured = false;

        // 1. Run UI Logic
        egui_macroquad::ui(|ctx| {
            captured = ctx.wants_pointer_input() || ctx.wants_keyboard_input();
            viz.draw_ui_content(ctx);
        });

        // 2. Handle Scene Inputs
        if !captured {
            viz.handle_input(dt);
        }

        if viz.should_quit() {
            break;
        }

        // 3. Update & Render Scene
        let mut sim_start = 0.0;
        let mut sim_duration = 0.0;

        let steps_per_frame = if viz.running { viz.speed_multiplier } else { 1 };

        if viz.running {
            for _ in 0..steps_per_frame {
                viz.update(dt);
            }
        } else {
            viz.update(dt);
        }

        // --- RENDER PREP (LOD SYSTEM) ---
        let mut tex_offset = vec2(0.0, 0.0);
        let mut tex_dest_size = vec2(
            viz.grid_width as f32 * TILE_SIZE,
            viz.grid_height as f32 * TILE_SIZE,
        );
        let mut is_satellite = false;

        #[cfg(feature = "gpu-prototype")]
        {
            if let Some(gpu) = &viz.gpu_sim {
                // Determine Viewport
                let screen_w = screen_width();
                let screen_h = screen_height();
                let half_w = screen_w / (2.0 * viz.zoom * TILE_SIZE);
                let half_h = screen_h / (2.0 * viz.zoom * TILE_SIZE);
                let center_x = viz.camera_pos.x / TILE_SIZE;
                let center_y = viz.camera_pos.y / TILE_SIZE;

                let view_x = (center_x - half_w).floor() as i32;
                let view_y = (center_y - half_h).floor() as i32;
                let view_w = (half_w * 2.0).ceil() as i32;
                let view_h = (half_h * 2.0).ceil() as i32;

                // Threshold: If we see more than ~2000 tiles wide, switch to Satellite
                let use_satellite = viz.zoom < 0.05;

                if use_satellite {
                    is_satellite = true;

                    // Satellite Readback
                    if viz.running {
                        gpu.downsample();
                    }
                    let frame_bytes = gpu.capture_satellite().await;
                    let image = Image {
                        width: 4096,
                        height: 4096,
                        bytes: frame_bytes,
                    };

                    // Reuse satellite texture if it exists
                    if let Some(tex) = &viz.cached_satellite_texture {
                        tex.update(&image);
                    } else {
                        let texture = Texture2D::from_image(&image);
                        texture.set_filter(FilterMode::Linear);
                        viz.cached_satellite_texture = Some(texture);
                    }

                    // Use cached satellite texture (always maps to full grid)
                    gpu_texture = viz.cached_satellite_texture.clone();
                    tex_offset = vec2(0.0, 0.0);
                    tex_dest_size = vec2(
                        viz.grid_width as f32 * TILE_SIZE,
                        viz.grid_height as f32 * TILE_SIZE,
                    );
                } else {
                    // Detail Mode (ROI)
                    let x = view_x.max(0) as u32;
                    let y = view_y.max(0) as u32;
                    // Clamp to max texture size (4096) AND grid dimensions (to match capture return size)
                    let w = view_w
                        .clamp(1, 4096) // Limit to 4k texture
                        .min(viz.grid_width as i32 - x as i32)
                        .max(1) as u32;
                    let h = view_h
                        .clamp(1, 4096)
                        .min(viz.grid_height as i32 - y as i32)
                        .max(1) as u32;

                    // Always readback in detail mode (Original behavior)
                    let frame_bytes = gpu.capture_frame_roi(x, y, w, h).await;
                    let state_data = gpu.capture_state_roi(x, y, w, h).await;

                    if !frame_bytes.is_empty() {
                        let image = Image {
                            width: w as u16,
                            height: h as u16,
                            bytes: frame_bytes,
                        };

                        // Reuse ROI texture if dimensions match
                        let mut reused = false;
                        if let Some(tex) = &viz.cached_roi_texture {
                            if tex.width() == image.width as f32
                                && tex.height() == image.height as f32
                            {
                                tex.update(&image);
                                reused = true;
                            }
                        }

                        if !reused {
                            let texture = Texture2D::from_image(&image);
                            texture.set_filter(FilterMode::Nearest);
                            viz.cached_roi_texture = Some(texture);
                        }

                        // Register text overlays disabled - too janky and kills FPS
                        // viz.render_overlays_gpu(&state_data, x, y, w, h);
                        viz.last_roi_state = Some((x, y, w, h, state_data));
                    }

                    gpu_texture = viz.cached_roi_texture.clone();
                    tex_offset = vec2(x as f32 * TILE_SIZE, y as f32 * TILE_SIZE);
                    tex_dest_size = vec2(w as f32 * TILE_SIZE, h as f32 * TILE_SIZE);
                }
            }
        }

        #[cfg(feature = "gpu-prototype")]
        viz.render_scene(
            gpu_texture.as_ref(),
            tex_offset,
            tex_dest_size,
            is_satellite,
        );

        #[cfg(not(feature = "gpu-prototype"))]
        viz.render_scene(None, tex_offset, tex_dest_size, false);

        // 4. Draw UI
        egui_macroquad::draw();

        next_frame().await
    }
}

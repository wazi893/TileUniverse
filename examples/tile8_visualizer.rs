    // Helper: Get tile type (works in both GPU and CPU mode)
    #[inline]
    fn get_tile_type_at(&self, x: usize, y: usize) -> TileType {
        #[cfg(feature = "gpu-prototype")]
        {
            let idx = y * self.grid_width + x;
            if idx < self.tile_types.len() {
                // Convert u8 back to TileType
                unsafe { std::mem::transmute::<u8, TileType>(self.tile_types[idx]) }
            } else {
                TileType::Wire
            }
        }
        #[cfg(not(feature = "gpu-prototype"))]
        {
            self.sim.get_tile_type(x, y)
        }
    }

    // Helper: Get tile value (CPU mode: from sim, GPU mode: from readback or 0)
    #[inline]
    fn get_tile_value_at(&self, x: usize, y: usize) -> u64 {
        #[cfg(feature = "gpu-prototype")]
        {
            // In GPU mode, check if we have readback data for this tile
            if let Some((rx, ry, rw, rh, ref data)) = self.last_roi_state {
                let tx = x as u32;
                let ty = y as u32;
                if tx >= rx && tx < rx + rw && ty >= ry && ty < ry + rh {
                    let local_x = tx - rx;
                    let local_y = ty - ry;
                    let idx = (local_y * rw + local_x) as usize;
                    if idx < data.len() {
                        return data[idx] as u64;
                    }
                }
            }
            0 // No readback data available
        }
        #[cfg(not(feature = "gpu-prototype"))]
        {
            self.sim.get_tile_value(x, y)
        }
    }

    fn handle_input(&mut self, dt: f32) {
        // Smooth zoom - improved responsiveness
        let wheel = mouse_wheel().1;
        if wheel != 0.0 {
            // Logarithmic zoom for consistent feel across zoom levels
            let zoom_factor = if wheel > 0.0 { 1.25 } else { 0.8 };
            self.target_zoom = (self.target_zoom * zoom_factor).clamp(MIN_ZOOM, MAX_ZOOM);
        }

        // Mouse drag pan
        if is_mouse_button_down(MouseButton::Right) {
            // Changed Pan to Right Click to free Left Click for Drawing
            let delta = mouse_delta_position();
            self.camera_pos.x -= delta.x / self.zoom;
            self.camera_pos.y -= delta.y / self.zoom;
        }

        // Mouse Draw (Left Click) - Only in Edit Mode
        if self.edit_mode && is_mouse_button_down(MouseButton::Left) {
            let mpos = mouse_position();
            let screen_w = screen_width();
            let screen_h = screen_height();
            let world_x = self.camera_pos.x + (mpos.0 - screen_w * 0.5) / self.zoom;
            let world_y = self.camera_pos.y + (mpos.1 - screen_h * 0.5) / self.zoom;
            let tile_x = (world_x / TILE_SIZE).floor() as i32;
            let tile_y = (world_y / TILE_SIZE).floor() as i32;

            if tile_x >= 0
                && tile_x < self.grid_width as i32
                && tile_y >= 0
                && tile_y < self.grid_height as i32
            {
                #[cfg(feature = "gpu-prototype")]
                if let Some(gpu) = &self.gpu_sim {
                    let type_id = match self.current_tool {
                        Tool::Wire => 0,
                        Tool::And => 1,
                        Tool::Or => 2,
                        Tool::Xor => 3,
                        Tool::Clock => 7,
                        Tool::Const => 30,
                        Tool::Not => 4,
                        Tool::CpuHead => 40,
                        Tool::Register => 41,
                        Tool::Console => 42,
                        Tool::Selector => 48,
                        Tool::Eraser => 255,
                    };
                    gpu.update_tile(tile_x as u32, tile_y as u32, type_id);

                    // If we are painting a State-carrying tile, inject a pulse!
                    // This allows the user to trigger the "Ripple" manually.
                    if type_id == 30 || type_id == 41 || type_id == 42 {
                        gpu.update_state(tile_x as u32, tile_y as u32, 255);
                    }
                }
            }
        }

        // Mouse select CPU (Left click released - for selection)
        if is_mouse_button_released(MouseButton::Left) {
            let mpos = mouse_position();
            let screen_w = screen_width();
            let screen_h = screen_height();

            // Adjust for camera center
            let world_x = self.camera_pos.x + (mpos.0 - screen_w * 0.5) / self.zoom;
            let world_y = self.camera_pos.y + (mpos.1 - screen_h * 0.5) / self.zoom;

            let tile_x = (world_x / TILE_SIZE).floor() as i32;
            let tile_y = (world_y / TILE_SIZE).floor() as i32;

            if tile_x >= 0 && tile_y >= 0 {
                #[cfg(feature = "gpu-prototype")]
                {
                    if let Some(id) = self
                        .cpu_grid
                        .get_cpu_at_tile(tile_x as usize, tile_y as usize)
                    {
                        self.selected_cpu_index = Some(id);
                        self.inspector_open = true;
                    }
                }

                #[cfg(not(feature = "gpu-prototype"))]
                {
                    let cpu_size_tiles = self.cpu_spacing as i32;
                    for (idx, cpu) in self.cpus.iter().enumerate() {
                        let (ox, oy) = cpu.cpu.origin;
                        let ox = ox as i32;
                        let oy = oy as i32;
                        if tile_x >= ox
                            && tile_x < ox + cpu_size_tiles
                            && tile_y >= oy
                            && tile_y < oy + cpu_size_tiles
                        {
                            self.selected_cpu_index = Some(idx);
                            self.inspector_open = true;
                            break;
                        }
                    }
                }
            }
        }

        // Keyboard zoom
        if is_key_down(KeyCode::Q) {
            self.target_zoom = (self.target_zoom * (1.0 + 2.0 * dt)).clamp(MIN_ZOOM, MAX_ZOOM);
        }
        if is_key_down(KeyCode::E) {
            self.target_zoom = (self.target_zoom * (1.0 - 2.0 * dt)).clamp(MIN_ZOOM, MAX_ZOOM);
        }

        // WASD pan
        let pan_amount = PAN_SPEED * dt / self.zoom;
        if is_key_down(KeyCode::W) || is_key_down(KeyCode::Up) {
            self.camera_pos.y -= pan_amount;
        }
        if is_key_down(KeyCode::S) || is_key_down(KeyCode::Down) {
            self.camera_pos.y += pan_amount;
        }
        if is_key_down(KeyCode::A) || is_key_down(KeyCode::Left) {
            self.camera_pos.x -= pan_amount;
        }
        if is_key_down(KeyCode::D) || is_key_down(KeyCode::Right) {
            self.camera_pos.x += pan_amount;
        }

        // Shortcuts
        if is_key_pressed(KeyCode::Key1) {
            self.target_zoom = 3.5;
        }
        if is_key_pressed(KeyCode::Key2) {
            self.target_zoom = 1.2;
        }
        if is_key_pressed(KeyCode::Key3) {
            self.target_zoom = 0.12;
        }
        if is_key_pressed(KeyCode::Key4) {
            self.target_zoom = 0.004;
        } // Satellite View (10k scale)
        if is_key_pressed(KeyCode::Space) {
            let center_x = (self.grid_width as f32 * TILE_SIZE) / 2.0;
            let center_y = (self.grid_height as f32 * TILE_SIZE) / 2.0;
            self.camera_pos = vec2(center_x, center_y);
            self.target_zoom = 0.05;
        }
        if is_key_pressed(KeyCode::R) {
            self.running = !self.running;
        }
        if is_key_pressed(KeyCode::F) {
            self.fullscreen = !self.fullscreen;
            set_fullscreen(self.fullscreen);
        }

        // Lerp zoom
        self.zoom = self.zoom + (self.target_zoom - self.zoom) * ZOOM_LERP_SPEED * dt;
    }

    fn should_quit(&self) -> bool {
        is_key_pressed(KeyCode::Escape)
    }

    fn update(&mut self, dt: f32) {
        self.time += dt;
        if self.running {
            #[cfg(feature = "gpu-prototype")]
            if let Some(gpu) = &mut self.gpu_sim {
                gpu.step();
                self.cycle_count += 1;
                // Don't return, let the update loop continue if we need other cpu-side effects
                // But for now, returning prevents double-sim.
                return;
            }

            // Use TRUE PHYSICS (slow but real) - CPU-only fallback
            #[cfg(not(feature = "gpu-prototype"))]
            {
                run_all_cpus(&mut self.sim, &self.cpus, 1);
                self.cycle_count += 1;
            }
        }
    }

    fn render_scene(
        &self,
        gpu_texture: Option<&Texture2D>,
        tex_offset: Vec2,
        tex_dest_size: Vec2,
        is_satellite: bool,
    ) {
        let screen_w = screen_width();
        let screen_h = screen_height();

        set_camera(&Camera2D {
            target: self.camera_pos,
            zoom: vec2(self.zoom * 2.0 / screen_w, self.zoom * 2.0 / screen_h),
            ..Default::default()
        });

        // Visible region
        let half_w = screen_w / (2.0 * self.zoom);
        let half_h = screen_h / (2.0 * self.zoom);
        let view_left = self.camera_pos.x - half_w;
        let view_right = self.camera_pos.x + half_w;
        let view_top = self.camera_pos.y - half_h;
        let view_bottom = self.camera_pos.y + half_h;

        // GPU Prototype Override
        let rendered_gpu = if let Some(tex) = gpu_texture {
            // LAYER 1: Background Layout (Rainbow Blocks)
            // Draw this BEHIND the logic texture if we are zoomed out and it is satellite view (transparency issues?)
            // Satellite texture is solid, so it covers blocks.
            // If we are in LOD_BLOCKS range, we might want to blend?

            if is_satellite && self.zoom < 0.2 {
                self.render_cpu_blocks(view_left, view_right, view_top, view_bottom);
            }

            // LAYER 2: Logic Texture (Wires & Gates)

            let params = DrawTextureParams {
                dest_size: Some(tex_dest_size),
                ..Default::default()
            };
            // tex.set_filter(FilterMode::Nearest); // Already set in main

            // For ROI, tex_offset is the world position of the top-left of the texture.
            draw_texture_ex(tex, tex_offset.x, tex_offset.y, WHITE, params);
            true
        } else {
            false
        };

        if !rendered_gpu {
            if self.zoom >= LOD_GATES {
                self.render_tiles(view_left, view_right, view_top, view_bottom);
            } else if self.zoom >= LOD_CPUS {
                self.render_cpu_blocks(view_left, view_right, view_top, view_bottom);
            } else {
                self.render_pixel_grid(view_left, view_right, view_top, view_bottom);
            }
        }
        // Note: render_cpu_blocks is already called before the texture at zoom < 0.2 (line 866-868)
        // No need to call it again here - that was causing double rendering and FPS drops

        // Only show grid when zoomed in enough to see individual cells (zoom >= 0.3)
        if self.show_grid && self.zoom >= 0.3 {
            self.render_grid_overlay(view_left, view_right, view_top, view_bottom);
        }

        // Render quantum amplitude heatmap (Sprint 57.0 Phase 5)
        // Note: This switches to screen space, so we restore world camera after
        self.render_amplitude_heatmap();

        // Restore world camera after heatmap overlay
        set_camera(&Camera2D {
            target: self.camera_pos,
            zoom: vec2(self.zoom * 2.0 / screen_w, self.zoom * 2.0 / screen_h),
            ..Default::default()
        });

        // Highlight selection
        if let Some(idx) = self.selected_cpu_index {
            #[cfg(feature = "gpu-prototype")]
            let cpu_opt = self.cpu_grid.get_cpu(idx).map(|c| (c.cpu.origin, idx));

            #[cfg(not(feature = "gpu-prototype"))]
            let cpu_opt = self.cpus.get(idx).map(|c| (c.cpu.origin, idx));

            if let Some(((ox, oy), _id)) = cpu_opt {
                let px = ox as f32 * TILE_SIZE;
                let py = oy as f32 * TILE_SIZE;
                let size = self.cpu_spacing as f32 * TILE_SIZE;
                let pulse = (self.time * 5.0).sin() * 0.5 + 0.5;
                let color = Color::new(1.0, 1.0, 0.0, 0.5 + 0.5 * pulse);
                draw_rectangle_lines(
                    px - 2.0,
                    py - 2.0,
                    size + 4.0,
                    size + 4.0,
                    4.0 / self.zoom,
                    color,
                );
            }
        }

        set_default_camera();
    }

    fn render_tiles(&self, left: f32, right: f32, top: f32, bottom: f32) {
        let tile_left = ((left / TILE_SIZE).floor() as i32).max(0) as usize;
        let tile_right =
            ((right / TILE_SIZE).ceil() as i32).clamp(0, self.grid_width as i32) as usize;
        let tile_top = ((top / TILE_SIZE).floor() as i32).max(0) as usize;
        let tile_bottom =
            ((bottom / TILE_SIZE).ceil() as i32).clamp(0, self.grid_height as i32) as usize;

        if tile_right <= tile_left || tile_bottom <= tile_top {
            return;
        }

        let tile_count = (tile_right - tile_left) * (tile_bottom - tile_top);
        let (max_tiles, step) = if self.zoom >= 0.7 {
            (25000, 1usize)
        } else {
            let max = 8000;
            let s = if tile_count > max {
                ((tile_count as f32 / max as f32).sqrt().ceil() as usize).max(1)
            } else {
                1
            };
            (max, s)
        };

        let mut drawn = 0;
        for y in (tile_top..tile_bottom).step_by(step) {
            for x in (tile_left..tile_right).step_by(step) {
                if drawn >= max_tiles {
                    return;
                }
                let tile_type = self.get_tile_type_at(x, y);
                let value = self.get_tile_value_at(x, y);
                let px = x as f32 * TILE_SIZE;
                let py = y as f32 * TILE_SIZE;
                let size = TILE_SIZE * step as f32 - 1.0;
                let color = tile_type_color(tile_type, value);
                draw_rectangle(px, py, size, size, color);
                drawn += 1;
            }
        }
    }


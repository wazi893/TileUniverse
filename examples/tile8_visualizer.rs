fn format_thousands(n: usize) -> String {
    let s = n.to_string();
    let mut result = String::new();
    for (i, c) in s.chars().rev().enumerate() {
        if i > 0 && i % 3 == 0 {
            result.push(',');
        }
        result.push(c);
    }
    result.chars().rev().collect()
}

/// Convert a graph to OpenQASM 3.0 circuit that creates its graph state.
/// Graph state construction: H on all qubits, then CZ for each edge.
fn graph_to_qasm3(g: &Graph) -> String {
    let mut qasm = String::new();
    qasm.push_str("// Graph State Circuit (OpenQASM 3.0)\n");
    qasm.push_str("// Generated by TileUniverse Sprint 57.0\n");
    qasm.push_str(&format!(
        "// Graph: {} vertices, {} edges\n\n",
        g.n_vertices,
        g.num_edges()
    ));
    qasm.push_str("OPENQASM 3.0;\n");
    qasm.push_str("include \"stdgates.inc\";\n\n");
    qasm.push_str(&format!("qubit[{}] q;\n\n", g.n_vertices));

    // Step 1: Apply Hadamard to all qubits
    qasm.push_str("// Step 1: Initialize all qubits to |+> state\n");
    for i in 0..g.n_vertices {
        qasm.push_str(&format!("h q[{}];\n", i));
    }
    qasm.push('\n');

    // Step 2: Apply CZ for each edge
    if !g.edges.is_empty() {
        qasm.push_str("// Step 2: Apply CZ gates for graph edges\n");
        for (i, j) in &g.edges {
            qasm.push_str(&format!("cz q[{}], q[{}];\n", i, j));
        }
    }

    qasm
}


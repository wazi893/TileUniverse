fn value_to_heat(value: u8) -> Color {
    let v = value as f32 / 255.0;
    let hue = 0.7 - v * 0.9;
    let hue = if hue < 0.0 { hue + 1.0 } else { hue };
    let sat = 0.8;
    let val = 0.4 + v * 0.6;
    hsv_to_rgb(hue, sat, val)
}

fn cpu_color(r0: u8, cpu_id: usize, time_pulse: f32) -> Color {
    let hue = ((cpu_id * 37) % 360) as f32 / 360.0;
    let sat = 0.7 + (r0 as f32 / 255.0) * 0.3;
    let pulse = (time_pulse + (r0 as f32 / 64.0)).sin() * 0.1;
    let val = 0.5 + (r0 as f32 / 255.0) * 0.5 + pulse;
    hsv_to_rgb(hue, sat, val.clamp(0.3, 1.0))
}

/// Map probability to heatmap color (Sprint 57.0 Phase 5)
/// Uses viridis-like colormap: purple (low) -> blue -> green -> yellow (high)
fn probability_to_color(prob: f64, max_prob: f64, log_scale: bool) -> Color {
    if prob <= 0.0 {
        return Color::new(0.0, 0.0, 0.0, 0.0); // Transparent for zero
    }

    let normalized = if log_scale {
        // Log scale: better for sparse states
        let log_prob = prob.log10();
        let log_max = max_prob.log10();
        let log_min = -15.0; // ~1e-15 minimum visible
        ((log_prob - log_min) / (log_max - log_min)).clamp(0.0, 1.0)
    } else {
        // Linear scale
        (prob / max_prob).clamp(0.0, 1.0)
    };

    let t = normalized as f32;

    // Viridis-inspired colormap
    let r = (0.267 + t * (0.993 - 0.267)).clamp(0.0, 1.0);
    let g = if t < 0.5 {
        0.004 + t * 2.0 * (0.565 - 0.004)
    } else {
        0.565 + (t - 0.5) * 2.0 * (0.906 - 0.565)
    };
    let b = if t < 0.5 {
        0.329 + t * 2.0 * (0.693 - 0.329)
    } else {
        0.693 - (t - 0.5) * 2.0 * (0.693 - 0.144)
    };

    Color::new(r, g.clamp(0.0, 1.0), b.clamp(0.0, 1.0), 0.8)
}

fn hsv_to_rgb(h: f32, s: f32, v: f32) -> Color {
    let c = v * s;
    let x = c * (1.0 - ((h * 6.0) % 2.0 - 1.0).abs());
    let m = v - c;
    let (r, g, b) = match (h * 6.0) as i32 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    Color::new(r + m, g + m, b + m, 1.0)
}

